/**
 * Belirli bir TR metni UI diline çevirir.
 *   • lang === "tr" → TR'yi olduğu gibi döner
 *   • lang === "en" → EN haritadan döner, yoksa TR fallback
 *   • lang === "ku" → TR döner (KU UI Türkçe çeviri gösterir)
 */
export function tx(lang: LangCode, tr: string): string {
  if (!tr) return tr;
  if (lang === "en") return TR_TO_EN[tr] ?? tr;
  return tr;
}

/**
 * Bir kelime dizisini UI diline çevirir (word bank için).
 */
export function txArr(lang: LangCode, items: string[]): string[] {
  return items.map((it) => tx(lang, it));
}
